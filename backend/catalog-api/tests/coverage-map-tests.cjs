const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const fits = [];
const paths = ['de', 'pl'].map((id, i) => ({id, style: {}, classList: {add(){}, remove(){}}, setAttribute(){}, addEventListener(){}, getBBox: () => ({x:480+i*20,y:90,width:20,height:25})}));
const svg = {getAttribute: () => '0 0 960 480', querySelectorAll: () => paths};
const map = {attributionControl: {setPrefix(){}, addAttribution(){}}, invalidateSize(){}, fitBounds(bounds, options){fits.push({bounds, options});}, on(){}, zoomIn(){}, zoomOut(){}, remove(){}};
const context = {window: {}, DOMParser: class {parseFromString(){return {documentElement: svg};}}, ResizeObserver: class {observe(){} disconnect(){}}, L: {CRS: {Simple: {}}, map: () => map, svgOverlay: () => ({addTo(){}}), latLngBounds: (...points) => ({points, pad(){return this;}, extend(pair){this.points.push(pair);}})}};
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname, '../src/terento_catalog/static/map/coverage-map-v1.js'), 'utf8'), context);
const coverage = context.window.TerentoCoverageMap({classList:{add(){}}, focus(){}}, {svg:''});
const world = fits.at(-1).bounds;
coverage.update([{code:'de',count:1},{code:'pl',count:2},{code:'unknown',count:100}]);
assert.notEqual(fits.at(-1).bounds, world);
assert.equal(fits.at(-1).bounds.points.length, 3);
assert.equal(fits.at(-1).options.maxZoom, 2);
assert.equal(fits.at(-1).options.animate, false);
const active = fits.at(-1).bounds;
const calls = fits.length;
coverage.update([{code:'pl',count:3},{code:'de',count:2}]);
assert.equal(fits.length, calls, 'Repeated country coverage preserves manual pan/zoom');
coverage.zoom('reset');
assert.equal(fits.at(-1).bounds, active);
coverage.update([]);
assert.equal(fits.at(-1).bounds, world);
coverage.update([{code:'unknown',count:1},{code:'de',count:0}]);
assert.equal(fits.at(-1).bounds, world);
coverage.destroy();
console.log('Coverage focus, reset, unchanged coverage and empty fallback PASS');
