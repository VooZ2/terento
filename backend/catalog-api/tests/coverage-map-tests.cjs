const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const fits = [];
const paths = ['de', 'pl'].map((id, i) => ({id, style: {}, classList: {add(){}, remove(){}}, setAttribute(){}, addEventListener(){}, getBBox: () => ({x:480+i*20,y:90,width:20,height:25})}));
const svg = {getAttribute: () => '0 0 960 480', querySelectorAll: () => paths};
let currentZoom;
let zoomend;
let displayedPercent;
const attributions = [];
const map = {attributionControl: {setPrefix(){}, addAttribution(value){attributions.push(value);}}, invalidateSize(){}, getBoundsZoom(){return -1;}, getZoom(){return currentZoom;}, setView(center, zoom, options){currentZoom = zoom; fits.push({center, zoom, options}); zoomend?.();}, on(event, callback){if(event === 'zoomend') zoomend = callback;}, zoomIn(){currentZoom += 1; zoomend();}, zoomOut(){currentZoom -= 1; zoomend();}, remove(){}};
const context = {window: {}, DOMParser: class {parseFromString(){return {documentElement: svg};}}, ResizeObserver: class {observe(){} disconnect(){}}, L: {CRS: {Simple: {}}, map: () => map, svgOverlay: () => ({addTo(){}}), latLngBounds: (...points) => ({points, pad(){return this;}, getCenter(){return [240,480];}})}};
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname, '../src/terento_catalog/static/map/coverage-map-v1.js'), 'utf8'), context);
const coverage = context.window.TerentoCoverageMap({classList:{add(){}}, focus(){}}, {svg:'', onZoom(zoom, initial){displayedPercent = Math.round(2 ** (zoom - initial) * 100);}});
assert.match(attributions[0], /OpenStreetMap contributors/);
assert.doesNotMatch(attributions[0], /Natural Earth/);
assert.equal(fits.at(-1).zoom, -.25);
assert.equal(Math.round(2 ** (fits.at(-1).zoom + 1) * 100), 168);
assert.equal(displayedPercent, 100);
coverage.zoom('in');
assert.equal(displayedPercent, 200);
coverage.zoom('out');
assert.equal(displayedPercent, 100);
coverage.zoom('out');
assert.equal(displayedPercent, 50);
coverage.update([{code:'de',count:1},{code:'pl',count:2},{code:'unknown',count:100}]);
assert.equal(fits.length, 1);
assert.equal(fits.at(-1).options.animate, false);
const calls = fits.length;
coverage.update([{code:'pl',count:3},{code:'de',count:2}]);
assert.equal(fits.length, calls, 'Repeated country coverage preserves manual pan/zoom');
coverage.zoom('reset');
assert.equal(displayedPercent, 100);
assert.equal(fits.at(-1).zoom, -.25);
assert.equal(fits.length, 2);
coverage.update([]);
assert.equal(fits.length, 2);
coverage.update([{code:'unknown',count:1},{code:'de',count:0}]);
assert.equal(fits.length, 2);
coverage.destroy();
console.log('Owner overview = 100%; zoom in/out/reset and data-independent navigation PASS');
